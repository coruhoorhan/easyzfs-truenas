const DICTS: Record<'es' | 'en' | 'tr', Record<I18nKey, string>> = { es, en, tr };
// Clave canónica webapp-shell; 'zfc-lang' (legacy zfsctl) se migra una vez.
const LANG_KEY = 'easyzfs-lang';
const LANG_KEY_LEGACY = 'zfc-lang';

let currentLang: 'es' | 'en' | 'tr' = 'es';
const subs = new Set<() => void>();

export function resolveLang(mode: LangMode): 'es' | 'en' | 'tr' {
  if (mode === 'auto') {
    const l = (navigator.language || 'es').toLowerCase();
    if (l.startsWith('tr')) return 'tr';
    if (l.startsWith('en')) return 'en';
    return 'es';
  }
  return mode;
}

export function getLangMode(): LangMode {
  const v = localStorage.getItem(LANG_KEY);
  if (v) return v as LangMode;
  const old = localStorage.getItem(LANG_KEY_LEGACY);
  if (old) {
    localStorage.setItem(LANG_KEY, old);
    localStorage.removeItem(LANG_KEY_LEGACY);
    return old as LangMode;
  }
  return 'auto';
}

export function setLangMode(mode: LangMode): void {
  localStorage.setItem(LANG_KEY, mode);
  currentLang = resolveLang(mode);
  document.documentElement.lang = currentLang;
  subs.forEach((f) => f());
}

export function initLang(): void {
  currentLang = resolveLang(getLangMode());
  document.documentElement.lang = currentLang;
}

// Traducción con interpolación simple {clave}
export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  let s = DICTS[currentLang][key] ?? DICTS.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

// Suscripción para re-render al cambiar de idioma
export function onLangChange(fn: () => void): () => void {
  subs.add(fn);
  return () => subs.delete(fn);
}

export function getCurrentLang(): 'es' | 'en' | 'tr' {
  return currentLang;
}
